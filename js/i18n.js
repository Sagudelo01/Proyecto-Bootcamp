const i18n = {
  lang: 'en',
  t(key) {
    return (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key;
  },
  fmt(key, params) {
    return this.t(key).replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? params[k] : `{${k}}`));
  },
  region(name) {
    if (this.lang === 'es') return REGION_NAMES.es[name] || name;
    return name;
  },
};

